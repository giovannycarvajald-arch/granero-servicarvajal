-- Granero Servicarvajal: esquema inicial de Supabase
-- Ejecutar completo en Supabase > SQL Editor > New query.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  cat text not null default 'Otros',
  price numeric(12,2) not null check (price >= 0),
  unit text not null default '',
  emoji text not null default '🛍️',
  available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  mode text not null check (mode in ('Domicilio','Recoger')),
  address text not null default '',
  pay text not null default 'Efectivo',
  notes text not null default '',
  items jsonb not null,
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'Recibido'
    check (status in ('Recibido','En preparación','Listo','Entregado','Cancelado')),
  created_at timestamptz not null default now()
);

-- Los administradores se registran en Supabase Auth y luego se agregan aquí.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_granero_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.admin_users enable row level security;

drop policy if exists "Public can read available products" on public.products;
create policy "Public can read available products"
on public.products for select
to anon, authenticated
using (available = true or public.is_granero_admin());

drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products"
on public.products for all
to authenticated
using (public.is_granero_admin())
with check (public.is_granero_admin());

drop policy if exists "Customers can create orders" on public.orders;
create policy "Customers can create orders"
on public.orders for insert
to anon, authenticated
with check (true);

drop policy if exists "Admins can read orders" on public.orders;
create policy "Admins can read orders"
on public.orders for select
to authenticated
using (public.is_granero_admin());

drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
on public.orders for update
to authenticated
using (public.is_granero_admin())
with check (public.is_granero_admin());

